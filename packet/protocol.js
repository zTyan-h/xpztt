    const STRIP = /[^0-9A-Fa-f]/g;

    function bufferToHex(buffer) {
        if (!buffer || buffer.byteLength === 0) return '';
        return Array.from(new Uint8Array(buffer))
            .map(b => b.toString(16).padStart(2, '0').toUpperCase())
            .join(' ');
    }

    function bufferToString(buffer) {
        if (!buffer || buffer.byteLength === 0) return '';
        try {
            return new TextDecoder('utf-8').decode(buffer).replace(/[^\x20-\x7E]/g, '\u00B7');
        } catch (e) { ctx.log.warn('bufferToString', e); return ''; }
    }

    function normalizeToArrayBuffer(data) {
        if (data == null) return null;
        if (data instanceof ArrayBuffer) return data;
        if (ArrayBuffer.isView(data)) {
            try { return data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength); }
            catch (e) { ctx.log.warn('normalize: view', e); return null; }
        }
        if (typeof data === 'string') {
            try {
                const enc = new TextEncoder().encode(data);
                return enc.buffer.slice(enc.byteOffset, enc.byteOffset + enc.byteLength);
            } catch (e) { ctx.log.warn('normalize: string', e); return null; }
        }
        return null;
    }

    function buildPacket(headerId, hexPayloadStr) {
        const cleanHex = String(hexPayloadStr ?? '').replace(STRIP, '');
        const payloadLen = cleanHex.length / 2;
        const buffer = new ArrayBuffer(4 + 2 + payloadLen);
        const view = new DataView(buffer);
        view.setInt32(0, 2 + payloadLen, false);
        view.setInt16(4, headerId, false);
        const u8 = new Uint8Array(buffer);
        for (let i = 0; i < payloadLen; i++) {
            u8[6 + i] = parseInt(cleanHex.substr(i * 2, 2), 16) || 0;
        }
        return buffer;
    }

    function hexToArrayBuffer(fullHex) {
        const clean = String(fullHex ?? '').replace(STRIP, '');
        const len = clean.length / 2;
        const buf = new ArrayBuffer(len);
        const u8 = new Uint8Array(buf);
        for (let i = 0; i < len; i++) {
            u8[i] = parseInt(clean.substr(i * 2, 2), 16) || 0;
        }
        return buf;
    }

    function parseData(data) {
        if (!(data instanceof ArrayBuffer) || data.byteLength < 6) return null;
        try {
            const view = new DataView(data);
            const header = view.getInt16(4, false);
            const fullHex = bufferToHex(data);
            const payloadBuf = data.slice(6);
            const payloadHex = bufferToHex(payloadBuf);
            return {
                header,
                fullHex,
                payloadHex,
                ascii: bufferToString(payloadBuf),
                byteLength: data.byteLength,
                payloadLength: data.byteLength - 6,
            };
        } catch (e) { ctx.log.warn('parseData', e); return null; }
    }


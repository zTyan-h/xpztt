    function nome(id, dir) {
        if (id == null) return null;
        const map = dir === 'SEND' ? OUT : IN;
        return map[id] ?? null;
    }

    function rotulo(id, dir) {
        const n = nome(id, dir);
        const prefix = dir === 'SEND' ? 'OUT' : 'IN';
        return n ? `${prefix}.${n}` : `${prefix}.${id}`;
    }

    ctx.Names = { OUT, IN, nome, rotulo };

    // ═══════════════════════════════════════════════════════════
    // PACKET FILTER — visual block e network drop
    // ═══════════════════════════════════════════════════════════
    function normHex(s) { return String(s ?? '').replace(/\s/g, '').toUpperCase(); }

    function matchPayload(packet, rule) {
        if (!rule) return false;
        const limpa = String(rule).trim();
        if (!limpa) return false;
        const regraHex = normHex(limpa);
        const ehHex = /^[0-9A-F]+$/.test(regraHex) && regraHex.length >= 2 && regraHex.length % 2 === 0;
        if (ehHex && packet.fullHex.replace(/\s/g, '').toUpperCase().includes(regraHex)) return true;
        if (packet.ascii && packet.ascii.includes(limpa)) return true;
        return false;
    }

    ctx.PacketFilter = {
        isVisualBlocked(packet) {
            if (!packet) return false;
            const s = ctx.state;
            if (s.blIds.has(packet.header)) return true;
            for (const rule of s.blPayloads) {
                if (matchPayload(packet, rule)) return true;
            }
            return false;
        },
        isNetworkDropped(packet) {
            if (!packet) return false;
            const s = ctx.state;
            if (s.dropIds.has(packet.header)) return true;
            for (const rule of s.dropPayloads) {
                if (matchPayload(packet, rule)) return true;
            }
            return false;
        },
        manageList(type, action, val) {
            const s = ctx.state;
            let targetSet, targetArr, storeKeyId, storeKeyStr;
            if (type === 'VISUAL') {
                targetSet = s.blIds; targetArr = s.blPayloads;
                storeKeyId = 'bl_ids'; storeKeyStr = 'bl_payloads';
            } else {
                targetSet = s.dropIds; targetArr = s.dropPayloads;
                storeKeyId = 'drop_ids'; storeKeyStr = 'drop_payloads';
            }
            if (action === 'ADD_ID' && !isNaN(val) && val !== '') { targetSet.add(Number(val)); ctx.storage.set(storeKeyId, [...targetSet]); }
            if (action === 'ADD_STR' && val && String(val).trim()) {
                const v = String(val).trim();
                if (!targetArr.includes(v)) targetArr.push(v);
                ctx.storage.set(storeKeyStr, targetArr);
            }
            if (action === 'REMOVE_ID' && !isNaN(val)) { targetSet.delete(Number(val)); ctx.storage.set(storeKeyId, [...targetSet]); }
            if (action === 'REMOVE_STR' && val) {
                const idx = targetArr.indexOf(val);
                if (idx > -1) targetArr.splice(idx, 1);
                ctx.storage.set(storeKeyStr, targetArr);
            }
            if (action === 'CLEAR') {
                targetSet.clear(); targetArr.length = 0;
                ctx.storage.set(storeKeyId, []); ctx.storage.set(storeKeyStr, []);
            }
        },
    };

